/**
 * Python/MSM Runtime — Execute Python MSM scripts.
 *
 * This module manages Python environment detection and MSM script execution.
 * All Python execution goes through the registry + JSON-stdin security boundary.
 *
 * Supported MSM libraries:
 *  - PyEMMA (pyemma.org) — mature, widely used
 *  - deeptime (deeptime-ml.github.io) — modern, VAMP-focused
 *  - MSMBuilder (msmbuilder.org) — classic
 */

import { fileURLToPath } from 'node:url'
import path from 'node:path'

/**
 * Check whether Python is available and has required MSM packages.
 * Returns { ok, packages, missing }.
 */
export async function checkPythonEnv(pythonPath, requiredPackages) {
  // In production: run `python -c "import pyemma; print(pyemma.__version__)"` etc.
  // For design: return the expected structure.
  return {
    ok: true,
    pythonPath,
    packages: requiredPackages.map(pkg => ({ name: pkg, available: true, version: '?.?.?' })),
    missing: [],
  }
}

/**
 * Generate a Python script for MSM construction.
 * The script reads JSON from stdin (per the json-stdin-v1 protocol)
 * and writes JSON to stdout.
 *
 * @param {object} config — Pipeline configuration
 * @returns {string} Python script text
 */
export function generateMsmScript(config) {
  // This generates a Python script that PyEMMA/deeptime can execute.
  // The script is NOT executed directly — it goes through the registry + ctx.shell.
  const lines = [
    '"""TH-MSM Pipeline Script — auto-generated by th_msm_build"""',
    'import json, sys, os',
    '',
    '# Read request from stdin',
    'request = json.load(sys.stdin)',
    'assert request.get("protocol") == "json-stdin-v1", "unsupported protocol"',
    '',
    'msm_name = request["msm"]',
    'args = request["args"]',
    '',
    '# Parse configuration',
    'config = json.loads(args[0]) if args else {}',
    '',
    'result = {"msm": msm_name, "steps": []}',
    '',
  ]

  // Step-by-step pipeline
  const steps = config.steps ?? ['preprocess', 'featurize', 'reduce', 'cluster', 'estimate']

  for (const step of steps) {
    switch (step) {
      case 'preprocess':
        lines.push(
          '# ── Preprocessing ──',
          `topology = config.get("topology_path", "")`,
          `trajectory = config.get("trajectory_path", "")`,
          'result["steps"].append({"step": "preprocess", "status": "ok"})',
        )
        break

      case 'featurize':
        lines.push(
          '# ── Featurization ──',
          'import pyemma.coordinates as coor',
          'feat = coor.featurizer(topology)',
          'feat.add_backbone_torsions()',
          'feat.add_residue_mindist()',
          'data = coor.load(trajectory, features=feat)',
          'result["steps"].append({"step": "featurize", "status": "ok", "n_features": feat.dimension()})',
        )
        break

      case 'reduce':
        lines.push(
          '# ── Dimensionality Reduction ──',
          'import pyemma.coordinates as coor',
          'tica = coor.tica(data, lag=config.get("lag_time", 10), dim=config.get("n_components", 5))',
          'tica_output = tica.get_output()',
          'result["steps"].append({"step": "reduce", "status": "ok", "method": "tica"})',
        )
        break

      case 'cluster':
        lines.push(
          '# ── Clustering ──',
          'import pyemma.coordinates as coor',
          'cluster = coor.cluster_kmeans(tica_output, k=config.get("n_clusters", 100), max_iter=500)',
          'dtrajs = cluster.dtrajs',
          'result["steps"].append({"step": "cluster", "status": "ok", "n_states": cluster.n_clusters})',
        )
        break

      case 'estimate':
        lines.push(
          '# ── MSM Estimation ──',
          'import pyemma.msm as msm',
          'its = msm.its(dtrajs, lags=config.get("its_lags", [1,2,5,10,20,50]), errors="bayes")',
          'M = msm.estimate_markov_model(dtrajs, lag=config.get("lag_time", 10))',
          'result["steps"].append({"step": "estimate", "status": "ok", "n_states": M.nstates})',
        )
        break

      case 'coarsegrain':
        lines.push(
          '# ── Coarse-graining (PCCA+) ──',
          'M.pcca(config.get("n_macrostates", 5))',
          'result["steps"].append({"step": "coarsegrain", "status": "ok"})',
        )
        break
    }
  }

  lines.push(
    '',
    '# Write result to stdout',
    'json.dump(result, sys.stdout)',
  )

  return lines.join('\n')
}

/**
 * Resolve the Python script path for a registered MSM command.
 * In production, this points to a pre-installed script in the workspace tools directory.
 */
export function resolvePythonScript(workspace, scriptName = 'msm_pipeline.py') {
  return path.join(workspace, 'tools', scriptName)
}