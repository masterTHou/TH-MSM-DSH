/**
 * th_msm_report — Generate a Markdown scientific report.
 *
 * Produces a complete MSM research report following the TH-MSM template:
 *
 *   1. Research Objective
 *   2. Data Description
 *   3. Method Rationale
 *   4. MSM Parameters
 *   5. Model Validation
 *   6. Major States
 *   7. Kinetic Interpretation
 *   8. Limitations
 *   9. Next Steps
 */

import { defineTool } from '@deepseek-ai/dsh-tools'

const resultSchema = {
  type: 'object',
  additionalProperties: false,
  properties: {
    ok: { type: 'boolean', required: true },
    reportPath: { type: 'string', required: true },
    report: { type: 'string', required: true },
    sectionsIncluded: {
      type: 'array', items: { type: 'string' }, required: true,
    },
    figuresGenerated: {
      type: 'array', items: { type: 'string' },
    },
  },
}

const REPORT_SECTIONS = [
  'research_objective',
  'data_description',
  'method_rationale',
  'msm_parameters',
  'model_validation',
  'major_states',
  'kinetic_interpretation',
  'limitations',
  'next_steps',
]

export function createReportTool(ctx, config) {
  return defineTool({
    name: 'th_msm_report',
    description:
      'Generate a comprehensive Markdown scientific report for a Markov State Model analysis. ' +
      'Includes all 9 standard sections from research objective to next steps. ' +
      'Optionally generates figures for ITS, CK test, and state populations.',
    parameters: {
      title: {
        type: 'string', required: true,
        description: 'Report title.',
      },
      modelPath: {
        type: 'string',
        description: 'Path to the MSM model file for data extraction.',
      },
      author: {
        type: 'string',
        description: 'Report author name.',
      },
      sections: {
        type: 'array',
        items: { type: 'string', enum: REPORT_SECTIONS },
        description: 'Sections to include. Default: all 9.',
      },
      generateFigures: {
        type: 'boolean',
        description: 'Generate ITS, CK, and population figures (default: true).',
      },
      outputDir: {
        type: 'string',
        description: 'Output directory for the report. Default: "output/reports".',
      },
    },
    output: {
      schema: resultSchema,
      render: (_args, value) => {
        if (!value.ok) return [{ type: 'text', text: 'Report generation failed.' }]
        return [
          { type: 'text', text: `Report saved to: ${value.reportPath}\n\nSections: ${value.sectionsIncluded.join(', ')}` },
          { type: 'text', text: value.report },
        ]
      },
    },
    timeoutMs: config.defaultTimeoutMs,
    isConcurrencySafe: () => true,

    async execute(args, exec) {
      const workspace = exec.agent?.session?.header?.cwd
      if (!workspace) {
        return {
          ok: false, reportPath: '', report: '',
          sectionsIncluded: [], figuresGenerated: [],
        }
      }

      const title = String(args.title ?? 'MSM Analysis Report')
      const author = args.author ?? 'TH-MSM Agent'
      const sections = args.sections ?? REPORT_SECTIONS
      const generateFigures = args.generateFigures ?? true
      const outputDir = args.outputDir ?? 'output/reports'
      const reportPath = `${workspace}/${outputDir}/msm_report.md`

      // Build the report from the template
      const report = generateReport(title, author, sections, {
        modelPath: args.modelPath,
        generateFigures,
      })

      // In production: write the report file via the workspace.
      // For design: return the full report text.

      const figuresGenerated = generateFigures
        ? ['figures/implied_timescales.png', 'figures/ck_test.png', 'figures/state_populations.png']
        : []

      return {
        ok: true,
        reportPath,
        report,
        sectionsIncluded: sections,
        figuresGenerated,
      }
    },
  })
}

// ── Report template generator ──────────────────────────────────

function generateReport(title, author, sections, opts) {
  const lines = [
    `# ${title}`,
    '',
    `**Author**: ${author}`,
    `**Date**: ${new Date().toISOString().slice(0, 10)}`,
    `**Generated by**: TH-MSM DSH Plugin v1.0`,
    '',
    '---',
    '',
  ]

  const sectionGenerators = {
    research_objective: () => [
      '## 1. Research Objective',
      '',
      '[Describe the scientific question this MSM addresses. What dynamical process are you studying? ' +
      'What timescale? What is the expected outcome?]',
      '',
    ],

    data_description: () => [
      '## 2. Data Description',
      '',
      '| Property | Value |',
      '|----------|-------|',
      '| System | [system name] |',
      '| Number of atoms | [N] |',
      '| Number of trajectories | [N] |',
      '| Total simulation time | [time] |',
      '| Time step | [dt] |',
      '| Temperature | [T] K |',
      '| Force field | [FF] |',
      '| Solvent model | [solvent] |',
      '',
      `Model file: \`${opts.modelPath ?? 'N/A'}\``,
      '',
    ],

    method_rationale: () => [
      '## 3. Method Rationale',
      '',
      '### Featurization',
      '[Why were these features chosen? What do they capture?]',
      '',
      '### Dimensionality Reduction',
      '[Why tICA/PCA/VAMP? How many components?]',
      '',
      '### Clustering',
      '[Why K-Means/GMM/HDBSCAN? How many states?]',
      '',
      '### Lag Time Selection',
      '[What τ was chosen? How was it determined? Show ITS analysis.]',
      '',
    ],

    msm_parameters: () => [
      '## 4. MSM Parameters',
      '',
      '| Parameter | Value |',
      '|-----------|-------|',
      '| Lag time (τ) | [value] |',
      '| Number of microstates | [N] |',
      '| Number of tICA components | [N] |',
      '| Reversible | yes |',
      '| Estimation method | Maximum Likelihood |',
      '| Number of macrostates (PCCA+) | [N] |',
      '',
    ],

    model_validation: () => [
      '## 5. Model Validation',
      '',
      '### Implied Timescale Analysis',
      '[ITS plot interpretation: do timescales converge at the chosen τ?]',
      '',
      '### Chapman-Kolmogorov Test',
      '[CK test results: does the model predict the observed dynamics?]',
      '',
      '### Population Analysis',
      '[Compare MSM stationary distribution to MD sampling.]',
      '',
      '### Model Stability',
      '[Bootstrap results: how robust are the timescales and populations?]',
      '',
    ],

    major_states: () => [
      '## 6. Major States',
      '',
      '| Macrostate | Population (%) | Dominant Feature |',
      '|------------|----------------|------------------|',
      '| State 1 | [%] | [description] |',
      '| State 2 | [%] | [description] |',
      '| ... | | |',
      '',
      '### Transition Network',
      '[Describe the most probable transition pathways.]',
      '',
    ],

    kinetic_interpretation: () => [
      '## 7. Kinetic Interpretation',
      '',
      '### Timescales',
      '[What are the dominant implied timescales (ITS) and what processes do they correspond to?]',
      '',
      '### Transition Pathways',
      '[What are the most probable pathways between major states? Use TPT if applicable.]',
      '',
      '### MFPTs (Mean First Passage Times)',
      '[What are the characteristic transition times?]',
      '',
    ],

    limitations: () => [
      '## 8. Limitations',
      '',
      '- [ ] Limited sampling of rare events',
      '- [ ] Finite trajectory length may miss slow processes',
      '- [ ] Discretization error from clustering',
      '- [ ] Feature choice may miss relevant degrees of freedom',
      '- [ ] MSM assumes Markovian dynamics at lag time τ',
      '- [ ] Bootstrap uncertainty: [describe]',
      '',
    ],

    next_steps: () => [
      '## 9. Next Steps',
      '',
      '- [ ] Run adaptive sampling to fill undersampled regions',
      '- [ ] Test alternative featurizations',
      '- [ ] Compare with enhanced sampling (MetaD, REHT)',
      '- [ ] Apply TPT for pathway analysis',
      '- [ ] Integrate with QM calculations on representative structures (TH-MSM → AutoREST)',
      '- [ ] Publish the MSM model and data',
      '',
    ],
  }

  for (const section of sections) {
    if (sectionGenerators[section]) {
      lines.push(...sectionGenerators[section]())
    }
  }

  if (opts.generateFigures) {
    lines.push(
      '---',
      '',
      '## Figures',
      '',
      '![Implied Timescales](figures/implied_timescales.png)',
      '',
      '![Chapman-Kolmogorov Test](figures/ck_test.png)',
      '',
      '![State Populations](figures/state_populations.png)',
      '',
    )
  }

  lines.push(
    '---',
    '',
    `*Report generated by TH-MSM DSH Plugin v1.0 on ${new Date().toISOString()}*`,
  )

  return lines.join('\n')
}